const applyBootstrapThemeVars = (palette: Record<string, string>) => {
  const varMap: Array<[string, string]> = [
    ['--bs-primary', palette.themePrimary],
    ['--bs-secondary', palette.themeSecondary],
    ['--bs-link-color', palette.link],
    ['--bs-link-hover-color', palette.linkHover],
    ['--bs-body-bg', palette.background],
    ['--bs-body-color', palette.foreground],
    ['--bs-tertiary-bg', palette.panel],
    ['--bs-secondary-bg', palette.neutralSidebar],
    ['--bs-border-color', palette.panelBorder],
    ['--bs-input-bg', palette.inputBackground],
    ['--bs-input-color', palette.inputForeground],
    ['--bs-emphasis-color', palette.foreground],
    ['--bs-heading-color', palette.foreground],
    ['--bs-text-color', palette.foreground],
    ['--elementor-builder-primary', palette.themePrimary],
    ['--elementor-builder-secondary', palette.themeSecondary],
    ['--elementor-builder-accent', palette.themeAccent],
    ['--elementor-builder-background', palette.background],
    ['--elementor-builder-panel', palette.panel],
    ['--elementor-builder-border', palette.panelBorder],
    ['--elementor-builder-foreground', palette.foreground],
    ['--elementor-builder-muted', palette.muted],
    ['--elementor-builder-link', palette.link],
    ['--elementor-builder-link-hover', palette.linkHover]
  ];

  if (typeof document !== 'undefined') {
    varMap.forEach(([key, value]) => document.documentElement.style.setProperty(key, value));
  }
};

export const getElementorBuilderTheme = (mode: elementorBuilderThemeMode): Record<string, string> => {
  const palette = THEME_MAP[mode] ?? THEME_MAP.dark;
  applyBootstrapThemeVars(palette);
  return palette;
};

export const getelementorBuilderTheme = getElementorBuilderTheme;

